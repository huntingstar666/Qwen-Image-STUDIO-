let locale = 'zh';

export const SUPPORTED_LOCALES = ['zh', 'en'];

export function setLocale(value) {
  locale = value === 'en' ? 'en' : 'zh';
  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
  return locale;
}

export function getLocale() {
  return locale;
}

/** 取词条并替换 {name} 占位符；缺失时回落到 fallback 或键名。 */
export function t(key, vars = {}, fallback = '') {
  const dict = DICTS[locale] || DICTS.zh;
  let text = dict[key] ?? DICTS.zh[key] ?? fallback ?? key;
  if (typeof text !== 'string') text = String(text);
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] != null ? String(vars[name]) : match);
}

/** 给静态 DOM 补齐 data-i18n 文案（设置页与壳层复用）。 */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n, {}, el.textContent);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle, {}, el.title);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria, {}, el.getAttribute('aria-label') || ''));
  }
}
